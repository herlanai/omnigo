package omniweb

import (
	"bytes"
	"encoding"
	"encoding/json"
	"fmt"
	"reflect"
	"strconv"
	"strings"
	"time"
)

// GenerateTypeScript emits a Services contract for the canonical OmniWebClient.
// It never executes handlers. Unsupported or ambiguous wire types fail instead
// of producing misleading declarations. Events and streams are not generated.
func GenerateTypeScript(router *Router) ([]byte, error) {
	if router == nil {
		return nil, fmt.Errorf("omniweb: router required")
	}
	g := typeScript{names: map[reflect.Type]string{}, active: map[reflect.Type]bool{}}
	var methods strings.Builder
	for _, method := range router.MethodTypes() {
		input, err := g.render(method.Request)
		if err != nil {
			return nil, fmt.Errorf("%s input: %w", method.Name, err)
		}
		output, err := g.render(method.Response)
		if err != nil {
			return nil, fmt.Errorf("%s output: %w", method.Name, err)
		}
		fmt.Fprintf(&methods, "  %s: { input: %s; output: %s };\n", strconv.Quote(method.Name), input, output)
	}
	var out bytes.Buffer
	out.WriteString("// Generated by OmniGo. Do not edit.\n// Use with OmniWebClient<Services> from the canonical SDK.\n\n")
	for _, definition := range g.definitions {
		out.WriteString(definition)
		out.WriteByte('\n')
	}
	out.WriteString("export type Services = {\n")
	out.WriteString(methods.String())
	out.WriteString("};\n")
	return out.Bytes(), nil
}

type typeScript struct {
	active      map[reflect.Type]bool
	names       map[reflect.Type]string
	definitions []string
}

var jsonMarshaler = reflect.TypeFor[json.Marshaler]()
var jsonUnmarshaler = reflect.TypeFor[json.Unmarshaler]()
var textMarshaler = reflect.TypeFor[encoding.TextMarshaler]()
var textUnmarshaler = reflect.TypeFor[encoding.TextUnmarshaler]()

func (g *typeScript) render(t reflect.Type) (string, error) {
	if t.Kind() == reflect.Struct {
		if name, ok := g.names[t]; ok {
			return name, nil
		}
	}
	if g.active[t] {
		return "", fmt.Errorf("recursive container requires a named struct DTO: %s", t)
	}
	g.active[t] = true
	defer delete(g.active, t)
	if t == reflect.TypeFor[json.RawMessage]() {
		return "unknown", nil
	}
	if t == reflect.TypeFor[time.Time]() {
		return "string", nil
	}
	if t == reflect.TypeFor[json.Number]() {
		return "number", nil
	}
	if t.Kind() == reflect.Pointer {
		value, err := g.render(t.Elem())
		return "(" + value + " | null)", err
	}
	for _, contract := range []reflect.Type{jsonMarshaler, jsonUnmarshaler, textMarshaler, textUnmarshaler} {
		if t.Implements(contract) || reflect.PointerTo(t).Implements(contract) {
			return "", fmt.Errorf("custom JSON/text codec requires explicit contract: %s", t)
		}
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean", nil
	case reflect.String:
		return "string", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr, reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Interface:
		if t.NumMethod() == 0 {
			return "unknown", nil
		}
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			if _, err := g.render(t.Elem()); err != nil {
				return "", err
			}
			return "(string | null)", nil
		}
		inner, err := g.render(t.Elem())
		if err != nil {
			return "", err
		}
		value := "Array<" + inner + ">"
		if t.Kind() == reflect.Slice {
			value = "(" + value + " | null)"
		}
		return value, nil
	case reflect.Map:
		switch t.Key().Kind() {
		case reflect.String, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		default:
			return "", fmt.Errorf("unsupported JSON map key %s", t.Key())
		}
		for _, contract := range []reflect.Type{textMarshaler, textUnmarshaler} {
			if t.Key().Implements(contract) {
				return "", fmt.Errorf("custom map key codec: %s", t.Key())
			}
		}
		inner, err := g.render(t.Elem())
		return "(Record<string, " + inner + "> | null)", err
	case reflect.Struct:
		if name, ok := g.names[t]; ok {
			return name, nil
		}
		name := fmt.Sprintf("Wire%d", len(g.names)+1)
		g.names[t] = name
		var body strings.Builder
		seen := map[string]bool{}
		for i := 0; i < t.NumField(); i++ {
			field := t.Field(i)
			tag := strings.Split(field.Tag.Get("json"), ",")
			if tag[0] == "-" {
				continue
			}
			if field.Anonymous {
				return "", fmt.Errorf("embedded field requires explicit wire DTO: %s.%s", t, field.Name)
			}
			if !field.IsExported() {
				continue
			}
			key := tag[0]
			if key == "" {
				key = field.Name
			}
			if seen[key] {
				return "", fmt.Errorf("ambiguous JSON field %q", key)
			}
			seen[key] = true
			value, err := g.render(field.Type)
			if err != nil {
				return "", err
			}
			optional := ""
			for _, option := range tag[1:] {
				switch option {
				case "omitempty", "omitzero":
					optional = "?"
				case "string":
					base := field.Type
					nullable := false
					if base.Kind() == reflect.Pointer {
						base = base.Elem()
						nullable = true
					}
					switch base.Kind() {
					case reflect.Bool, reflect.String, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr, reflect.Float32, reflect.Float64:
						value = "string"
						if nullable {
							value = "(string | null)"
						}
					}
				}
			}
			fmt.Fprintf(&body, "  %s%s: %s;\n", strconv.Quote(key), optional, value)
		}
		definition := "type " + name + " = {\n" + body.String() + "};\n"
		if len(seen) == 0 {
			definition = "type " + name + " = Record<string, never>;\n"
		}
		g.definitions = append(g.definitions, definition)
		return name, nil
	}
	return "", fmt.Errorf("unsupported JSON type %s", t)
}
